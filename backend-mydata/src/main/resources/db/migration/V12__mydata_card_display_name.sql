-- 실사용자가 카드마다 붙이는 표시 이름 (설계서 Phase 3 · F3).
--
-- 실사용자는 카드사별로 명세서를 따로 받으므로 카드도 여러 장이 된다. 어느 것이 어느 카드인지
-- 본인이 알아볼 이름이 필요한데, 그 이름을 **카탈로그(`card`)에 새 상품으로 만들지 않는다** —
-- 카탈로그는 실제 카드 상품 115종이 든 기준 데이터이고, 거기에 한 사람의 표기가 섞이면
-- 다음 사람에게도 보이는 가짜 상품이 된다.
--
-- 그래서 상품은 카탈로그에서 고르되(랜덤 포함) **표시명만 이 칸에 둔다.** 비어 있으면 화면은
-- 상품명을 그대로 쓴다.
ALTER TABLE mydata_card
    ADD COLUMN mydata_card_display_name VARCHAR(60) NULL;
