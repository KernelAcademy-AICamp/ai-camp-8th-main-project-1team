-- 실 마이데이터에 없는 두 칸을 **쓰지 않는 상태로 만든다** — 더미는 제약을 완화하는 게 아니라
-- 재현해야 한다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ★ 이 파일은 원래 `DROP COLUMN` 둘이었다. 지우지 않고 기본값만 주도록 바꿨다 (2026-08-12).
--
-- **왜 바꿨나 — 롤백이 롤백이 아니게 된다.**
--
-- 배포가 실패하면 `deploy-server.sh` 가 이전 커밋으로 되돌리는데, 되돌아가는 것은 **코드뿐이고
-- 스키마는 그대로다.** 칸을 지운 뒤에는 옛 코드가 없는 칸을 찾다가 죽어 **롤백해도 서버가
-- 살아나지 않는다.** `guard-main` 이 main 진입을 막은 이유가 이것이다.
--
-- **왜 그냥 두면 안 되나.** 두 칸 다 `int NOT NULL` 이고 기본값이 없다(운영에서 확인).
-- 엔티티에서 필드를 이미 뺐으므로 새 코드의 INSERT 는 값을 안 넣는다 →
-- `Field ... doesn't have a default value` 로 적재가 막힌다. 실사용자 명세서 적재
-- (`/self/import`)가 바로 그 경로다.
--
-- **그래서 기본값만 준다.** `ALTER COLUMN ... SET DEFAULT` 는 메타데이터만 바꾼다 —
-- `mydata_payment` 는 **1,100만 행**이라, 행을 다시 쓰는 변경이면 기동 중 헬스체크를 넘겨
-- 배포가 통째로 실패할 수 있다. 이 방식은 행을 건드리지 않는다.
--
-- **칸을 실제로 지우는 것은 다음 배포 몫이다.** 이번 배포가 안정된 뒤 새 번호로
-- `DROP COLUMN` 을 낸다. 그때는 되돌아갈 옛 코드가 이미 이 칸을 안 쓰므로 롤백이 성립한다.
-- guard 가 말한 "두 번에 나눠 내보내기"가 이것이다.
--
-- 실측(2026-08-12, 로컬 MySQL 9.7, `mydata_payment` 1,100만 행):
--     ALTER ... SET DEFAULT 0, ALGORITHM=INSTANT   →  0.09초
-- INSTANT 가 거부되지 않는다는 것이 곧 행을 다시 쓰지 않는다는 뜻이다.
--
-- ★ **이 파일을 이미 적용한 개발 DB 는 체크섬이 어긋난다.**
--   내용이 바뀌었으므로 Flyway 가 `Migration checksum mismatch for version 11` 로 기동을 막는다.
--   운영에는 적용된 적이 없어(운영 최신 V10) 규칙 3 위반이 아니고, 개발 DB 는 둘 중 하나로 푼다:
--       ./scripts/dev-up.sh 로 새로 만들거나,  mvn flyway:repair 로 체크섬을 갱신한다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ★ 왜 이 값들을 안 쓰기로 했나 (원본 근거)
--
-- 1) mydata_card_prev_month_amount (전월 실적액)
--    카드 업권 API 어디에도 전월 실적액 필드가 없다. 이 값을 제공자가 내주면 앱은 실적을
--    승인내역에서 계산할 이유가 없어지고, 그 계산이 없는 채로 실데이터를 맞는다.
--    게다가 생성기는 이 값을 `rnd.nextInt(650000)` 으로 만들었다 — 그 사람의 소비와
--    아무 관계가 없는 난수인데, 화면의 실적 진행바가 그 위에 얹혀 있었다.
--
-- 2) mydata_payment_received_benefit_amount (받은 혜택 금액)
--    할인·적립액 필드도 없다(카드-005 청구 추가정보·카드-008 승인내역 모두). 이 값은
--    위의 난수 실적구간으로 계산돼 결제마다 "−1,200원"으로 화면에 나갔다. 실데이터에는
--    그 숫자를 만들 근거가 없다.
--
-- 두 칸은 함께 다룬다. 혜택 계산이 실적구간 대조를 입구로 쓰기 때문에 하나만 손대면
-- 나머지가 공중에 뜬다.
--
-- 대량 생성 경로는 혜택을 이미 0으로만 넣고 있었다(GenerationRunner). 즉 실제로 값이
-- 들어 있던 것은 12명짜리 시드뿐이다.

ALTER TABLE mydata_card    ALTER COLUMN mydata_card_prev_month_amount          SET DEFAULT 0;
ALTER TABLE mydata_payment ALTER COLUMN mydata_payment_received_benefit_amount SET DEFAULT 0;
