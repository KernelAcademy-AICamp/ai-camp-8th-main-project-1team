-- 사용자에게 보이는 문장을 저장해 둔다 — 화면이 모델을 기다리지 않게 (2026-08-08)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 저장하나
--
-- 지금 리포트·프로필·절약후보의 문장은 **매 요청마다 모델을 부르거나**, 모델이 없으면 고정
-- 템플릿이다. 둘 다 문제가 있다 — 부르면 화면이 6~10초 기다리고, 템플릿이면 매번 같은 말이다.
--
-- 저장해 두면 셋이 한꺼번에 풀린다.
--   ① **화면이 안 기다린다.** 저장된 것을 즉시 그리고, 갱신은 뒤에서 한다.
--   ② **매번 다른 말을 하지 않는다.** 같은 화면을 두 번 열면 같은 문장이 보인다.
--   ③ **실패가 아무것도 안 망친다.** 새로 못 받으면 있던 문장이 그대로 남는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 언제 낡았다고 보나 — 두 가지 다
--
--   ① `generated_at` 이 24시간을 넘었다
--   ② `basis` 가 달라졌다 — **문장이 근거한 숫자가 바뀌었다**
--
-- ②가 없으면 "지난주 숫자로 쓴 문장이 오늘 숫자 옆에" 붙는다. 문장은 그때의 집계를 말로 옮긴
-- 것이라 숫자가 바뀌면 같이 낡는다. 특히 오늘 재분류가 리포트 캐시를 깨게 만들어서(§13-13)
-- 숫자는 하루에도 바뀐다.
--
-- 만료를 **날짜**가 아니라 **마지막 생성 + 24시간**으로 두는 것이 요점이다. 날짜로 두면 자정에
-- 전원의 문장이 한꺼번에 만료돼 23명 × 3종 = 69건이 동시에 밀려든다. 생성 시각이 사람마다
-- 흩어져 있으므로 이렇게 두면 몰림 자체가 안 생긴다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 '시도한 시각'을 따로 적나 — 실패가 무한 반복이 되는 자리
--
-- 큐에 넣는 트리거는 **사용자의 아무 상호작용**이고, 넣을지 말지는 "아직 필요한가"로 판단한다.
-- 성공하면 그 판단이 저절로 닫힌다 — 새 문장이 적히므로 다음 스캔이 필요 없다고 본다.
--
-- **실패하면 안 닫힌다.** 아무것도 안 적히므로 다음 상호작용이 같은 것을 또 넣고, 또 실패하고,
-- 사용자가 페이지를 넘길 때마다 그 짓을 반복한다. 예산을 통로 장애 하나가 통째로 먹는다.
--
-- 그래서 **시도했다는 사실**을 적는다. 이것과 "브랜드가 없다"를 적는 것은 다르다 —
--
--     ❌ "이 가맹점은 브랜드가 없다"        세계에 대한 거짓 (답을 못 받았을 뿐이다)
--     ✅ "우리가 이 시각에 시도했고 실패했다"  우리에 대한 참
--
-- 앞의 것은 통로 장애를 데이터로 굳히는 일이라 하면 안 되고(§13-13 의 '헛물'과 같은 이유),
-- 뒤의 것은 사실이라 적어도 된다. 사전이 `llm_attempts`·`last_attempt_at` 로 이미 같은 일을 한다(V21).
--
-- 그래서 **행은 첫 시도가 끝나는 순간 생긴다** — 성공이면 모델 문장으로, 실패면 고정 템플릿으로.
-- 어느 쪽이든 화면에 보여줄 것이 생기고, `attempted_at` 이 재시도 유예의 근거가 된다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 실물 여부를 칸으로 두나
--
-- `user_id` 가 키라 실사용자와 더미 행은 이미 안 섞인다 — 더미 행을 실사용자 것으로 읽을 길이
-- 없다. 그런데도 칸을 두는 이유는 **한 줄로 걷어내기 위해서**다.
--
--     DELETE FROM narrative_cache WHERE real_person = b'0';
--
-- V23·V24 가 브랜드 표와 판정 표에서 한 일이 그것이고, 그때 배운 것은 "골라 지울 수 있어야
-- 한다"였다. 표를 둘로 나누는 대신 칸 하나로 두면 조회 코드가 갈라지지 않는다.
--
-- 더미도 문장을 받는다 — 다만 **보조 차선의 맨 뒤**에서다(실사용자 것이 다 끝난 뒤). 무료
-- 통로라 값이 들지 않고, 데모 화면이 고정 템플릿만 보이는 것을 면한다.

CREATE TABLE narrative_cache (
    id           BIGINT       NOT NULL AUTO_INCREMENT,
    user_id      BIGINT       NOT NULL,
    -- 어느 화면의 문장인가 — REPORT / PROFILE / CUT_CANDIDATE.
    kind         VARCHAR(30)  NOT NULL,
    -- **같은 화면 안에서 다시 갈리는 축.** 절약 후보는 카테고리마다 다른 문장이다 —
    -- 이 칸이 없으면 (사용자, 화면) 한 행뿐이라 카페 문장이 쇼핑 화면에 뜨고 서로 덮어쓴다
    -- (2026-08-08 PR 직전 감사). 갈릴 것이 없는 화면(리포트·프로필)은 빈 문자열이다.
    subject      VARCHAR(60)  NOT NULL DEFAULT '',
    body         TEXT         NOT NULL,
    -- AI / TEMPLATE. 화면이 구별할 일은 없지만, 통로가 도는지 보는 단서다.
    source       VARCHAR(20)  NOT NULL,
    -- 이 문장이 근거한 숫자의 지문. 달라지면 낡은 것으로 본다.
    basis        VARCHAR(64)  NOT NULL,
    generated_at DATETIME     NOT NULL,
    -- **마지막으로 시도한 시각** — 성공·실패 무관. 실패가 무한 반복이 되지 않게 하는 근거다.
    -- 스캔은 "낡았는가" 다음에 "방금 시도해 보지 않았는가"를 함께 묻는다.
    attempted_at DATETIME     NOT NULL,
    -- 연속 실패 횟수. 0 이면 마지막 시도가 성공했다는 뜻이고, 쌓이면 유예를 늘린다.
    failures     INT          NOT NULL DEFAULT 0,
    -- 실제 사람의 문장인가. 더미 것만 걷어낼 수 있게 두는 칸이다.
    real_person  BIT(1)       NOT NULL DEFAULT b'0',
    PRIMARY KEY (id),
    -- 사용자 한 명의 한 화면·한 갈래에는 문장이 하나다.
    UNIQUE KEY uk_narrative_user_kind (user_id, kind, subject)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
