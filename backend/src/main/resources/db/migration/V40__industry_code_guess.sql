-- 업종코드를 **확정과 추정 두 층**으로 나눈다.
--
-- 실 명세서에는 업종코드가 없다. 그래서 적재기가 자리채움값을 넣고, 그 코드는 대조표에 없어
-- 카드 혜택축이 통째로 죽는다(cardAxisOf 가 업종코드를 읽는다). 실사용자 원장 2,135건 중
-- **1,653건(77%)**이 자리채움값이었다(2026-08-25 실측).
--
-- 채울 수 있는 것을 다 채워도 **확정은 40%가 한계**다. 소분류 170개 중 62개만 업종 하나를
-- 가리키고, 브랜드가 안 붙는 상호가 절반이다. 나머지는 추정할 수밖에 없다.
--
-- **그래서 칸을 가른다.** 한 칸에 섞으면 읽는 쪽이 추정을 사실로 쓴다 — category2 와
-- category2_llm 을 가른 것과 같은 이치이고, 같은 이유다(마스터 §4 원칙 1).
--
--   ksic_code              확정. 제공자가 준 값이거나 표에서 1:1 로 역산한 값
--   ksic_code_llm          추정. 모델이 답한 업종 이름을 코드로 옮긴 값
--
-- 추정 칸은 **판정에 참여하지 않는다.** 카드 혜택축도 확정 칸만 읽는다.

ALTER TABLE user_payment
    ADD COLUMN ksic_code_llm VARCHAR(8) NULL COMMENT '추정 업종코드 — 모델의 답에서 온다. 판정에 안 쓴다';

ALTER TABLE spending_ledger
    ADD COLUMN nts_industry_code_llm VARCHAR(8) NULL COMMENT '추정 업종코드. 확정(nts_industry_code)과 갈라 둔다';
