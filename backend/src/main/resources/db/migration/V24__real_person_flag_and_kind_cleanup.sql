-- 더미와 실물을 사용자 단위로 가르고, 더미가 채운 전역 판정을 걷어낸다 (2026-08-07)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ① 실물 표시를 사용자에 둔다
--
-- 지금까지 그 구분은 `user_payment.payment_id` 의 접두(`:real-`)라는 **문자열 관습** 하나였고,
-- 그것을 코드 여덟 자리가 각자 검사했다. 문제가 둘이다.
--
--   * **하나가 빠지면 조용히 샌다.** 실제로 관측 두 자리가 빠져 있었다(아래 ②).
--   * **값싼 조기 종료를 못 한다.** "이 사용자는 더미다"를 모르니 매 회차 결제를 전부 읽고
--     나서 버렸다 — 연동된 13명 중 12명이 더미인데 5분마다 3만 8천 행을 읽어 439건을
--     처리하고 있었다(2026-08-07 실측).
--
-- 그리고 `LIKE '%:real-%'` 는 앞에 와일드카드가 있어 인덱스를 못 탄다.
--
-- **손으로 켜는 값이 아니다.** 적재가 결제를 보면서 스스로 정한다 — 연동은 전부 지우고 다시
-- 넣으므로 그때마다 다시 계산되고, 증분은 덧붙이기만 하므로 켜기만 한다. 그래서 표시가
-- 데이터와 어긋날 자리가 없다. 아래 백필도 같은 술어를 쓴다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ② 더미가 채운 전역 판정을 걷어낸다
--
-- `business_number_kind` 는 사용자별 표가 아니라 **전역 판정 표**다. 한 사업자번호에 상호가
-- 여럿 보이면 "전부 같은 것을 파는가"를 판정해 두고, 사전 조회(`MerchantCategoryService.find` ⑤)
-- 가 **실사용자에게** 그 판정을 적용한다.
--
-- 그런데 관측하는 두 자리에 실사용자 게이트가 없었다.
--
--     MyDataLinkService.observeBusinessNumbers      연동·증분 동기화
--     MerchantCategoryController.observeAfterConfirm  더미 사용자가 화면에서 "맞아요"
--
-- 결과(2026-08-07 실측): **22행 중 20행이 더미 결제만으로** 만들어져 있었다.
--
--     business_number  kind    settled      실물건  더미건
--     1048183559       SINGLE  교통/자동차      31   1,119   ← 티머니
--     1298638970       UNKNOWN 교통/자동차      44   1,029
--     3968703587       UNKNOWN 쇼핑             17      76
--     (나머지 19행)                              0    2~139
--
-- 티머니가 특히 나쁘다. 생성기와 실제 사람이 **같이 쓰는 실재 번호**다. 판정에 쓰인 상호 8종은
-- 더미의 `티머니 · (주)티머니 · TMONEY · 온다택시` 이고, 실물 쪽 `카카오택시-서울33바2592` 류
-- 25종은 세어지지 않았다. `SINGLE` 로 굳으면 완화가 열려 **그 번호의 실사용자 결제 전부가
-- 형제 행의 분류를 물려받는다** — 생성기가 실사용자의 분류를 정하는 자리다.
--
-- **골라 지우지 않고 통째로 비운다.**
--
-- 처음에는 브랜드 표(V23)와 같은 술어 — "그 번호에 실제 사람의 결제가 있는가" — 를 쓰려 했다.
-- 그런데 그 술어는 **"이 판정이 무엇으로 만들어졌는가"를 말해 주지 않는다.** 티머니
-- (`1048183559`)는 생성기와 실제 사람이 같이 쓰는 실재 번호라 실물 결제가 31건 있고, 그래서
-- 안 지워진다 — 정작 그 행의 내용(`SINGLE`, 상호 8종)은 더미의 `티머니·TMONEY·온다택시` 로
-- 정해진 것인데도. 실측으로 22행 중 19행만 지워지고 문제의 3행이 남는다.
--
-- 그리고 남으면 **스스로 안 고쳐진다.** `merchant_names` 는 `Math.max` 라 줄지 않고, 한 번
-- `MULTI` 로 정해지면 관측으로는 되돌아오지 않는다(`BusinessNumberKindService.observe`).
-- 즉 더미가 정한 상태가 그대로 굳는다.
--
-- **비워도 잃는 것이 없다.** 이 표는 결제를 훑어 만든 파생 캐시이지 원본이 아니다. 행이 없으면
-- `relaxationAllowed` 는 `true` 를 돌려주므로(판정 이전 상태) 조회가 막히지도 않고, 그동안에도
-- `find()` ⑥ 의 `splitsIntoSeveralCategories`(확정 행이 두 중분류로 갈렸는가)가 독립적으로
-- 오염을 막는다. 방벽이 사라지는 것이 아니라 한 겹이 잠시 비는 것이다.
--
-- 재구축은 관측이 한다. 그리고 이제 관측은 **실물 결제만** 센다(`observeBusinessNumbers`).
-- 코드 쪽에서 후속 단계가 회차마다 관측을 다시 돌리므로, 실사용자는 다음 5분 안에 채워진다.

-- **`BIT(1)` 이라야 한다 — `BOOLEAN` 이 아니다.** MySQL 에서 `BOOLEAN` 은 `TINYINT(1)` 로
-- 만들어지는데, 이 저장소의 Java `boolean` 칸 열다섯은 예외 없이 `BIT(1)` 이다
-- (`app_user.consent_given` 부터 `guardian_*` 까지 — Hibernate 가 MySQL 방언에서 그렇게 만든다).
-- 운영은 `ddl-auto: validate` 라, 타입이 갈리면 드라이버의 `tinyInt1isBit` 기본값 하나에
-- 기동이 걸린다. 그때는 이미 적용된 마이그레이션이라 고칠 수도 없다(CLAUDE.md 규칙 3).
ALTER TABLE app_user
  ADD COLUMN real_person BIT(1) NOT NULL DEFAULT b'0';

UPDATE app_user u
   SET u.real_person = b'1'
 WHERE EXISTS (
    SELECT 1 FROM user_payment p
    WHERE p.user_id = u.id
      AND p.payment_id LIKE '%:real-%');

DELETE FROM business_number_kind;
