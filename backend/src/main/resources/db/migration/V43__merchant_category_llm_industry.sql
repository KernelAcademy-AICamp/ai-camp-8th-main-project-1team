-- **모델이 답한 업종 이름을 받아 적는다.**
--
-- `rememberGuess` 는 모델의 답에서 중분류만 계산하고 **업종 이름을 버렸다.** 그래서 사전의
-- 업종 이름 칸이 비고, 소분류를 이름에서 찾는 길(`stampSub`)이 끊긴다 — 브랜드가 안 붙는
-- 개인 상호는 소분류도 추정 업종코드도 영영 못 얻는다.
--
-- 실측(2026-08-25 운영): 브랜드도 소분류도 없는 사전 행 **280곳 중 260곳**에 업종 이름이
-- 아예 없었고, 그중 **67곳이 `LLM_GUESS`** 였다 — 모델은 답을 줬는데 우리가 안 적은 것이다.
--
-- **`registry_industry` 에 같이 담지 않는다.** 그 칸은 국세청 등록 업종, 곧 **사실**이고
-- `registryAnswered()` 가 그 칸으로 "조회를 이미 했다"를 판정한다. 추정을 거기 적으면
-- 순위가 뒤집힌다 — ③ 추정이 ②-b 등록 조회(사실)를 영영 막는다(§13-12).
--
--   registry_industry      사실. 국세청에 등록된 업종 이름
--   llm_industry           추정. 모델이 답한 업종 이름
--
-- 소분류를 찾을 때는 **사실을 먼저 보고** 없을 때만 추정을 본다.

ALTER TABLE merchant_category
    ADD COLUMN llm_industry VARCHAR(80) NULL COMMENT '추정 업종 이름 — 모델의 답. 사실(registry_industry)과 갈라 둔다';
