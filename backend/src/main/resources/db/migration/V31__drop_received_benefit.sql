-- 받은 혜택 금액 칸을 **쓰지 않는 상태로 만든다** — 실 마이데이터가 주지 않는 값이다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ★ 이 파일은 원래 칸 삭제(`ALTER ... DROP`) 였다. 지우지 않고 기본값만 주도록 바꿨다 (2026-08-12).
--
-- **왜 바꿨나 — 롤백이 롤백이 아니게 된다.**
--
-- 배포가 실패하면 `deploy-server.sh` 가 이전 커밋으로 되돌린다. 그런데 되돌아가는 것은
-- **코드뿐이고 스키마는 그대로다.** 컬럼을 지우는 마이그레이션이 한 번 돌고 나면, 되돌아간
-- 옛 코드는 없는 컬럼을 찾다가 죽는다 — **롤백해도 서버가 살아나지 않는다.**
-- `guard-main` 이 main 진입을 막은 이유가 이것이다.
--
-- **왜 그냥 두면 안 되나.**
--
-- 이 칸은 `int NOT NULL` 이고 **기본값이 없다**(운영에서 확인). 엔티티에서 필드를 이미 뺐으므로
-- 새 코드의 INSERT 는 이 칸에 값을 안 넣는다 → `Field 'received_benefit' doesn't have a default value`
-- 로 적재가 통째로 막힌다. 원 작성자가 지운 것은 그래서였다.
--
-- **그래서 기본값만 준다.**
--
--   · 새 코드 — 값을 안 넣어도 기본값이 들어가 INSERT 가 된다
--   · 옛 코드 — 칸이 그대로 있으므로 롤백해도 뜬다
--   · `ALTER COLUMN ... SET DEFAULT` 는 **메타데이터만 바꾼다** — 1,100만 행을 다시 쓰지 않아
--     기동 중 헬스체크가 넘어갈 위험도 없다(칸 삭제도 8.0.29+ 에서는 INSTANT 지만
--     이쪽이 더 확실하다)
--
-- **칸을 실제로 지우는 것은 다음 배포 몫이다.** 이번 배포가 운영에서 안정된 것을 확인한 뒤,
-- 새 번호로 칸을 실제로 없애는 마이그레이션을 하나 낸다. 그때는 되돌아갈 옛 코드가 이미 이 칸을
-- 안 쓰므로 롤백이 성립한다. 이것이 guard 가 말한 "두 번에 나눠 내보내기"다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ★ 번호 이력 (원본 주석 유지)
--
-- 이 파일은 V28 이었다. 번호만 V31 로 옮겼다 (2026-08-11) — develop 에 V28 이 이미 있었다
-- (`V28__guardian_tx_source_index.sql`, PR #161). 같은 버전 두 파일이면 Flyway 가
-- `Found more than one migration with version 28` 로 기동을 거부한다. git 은 파일 이름이
-- 달라 충돌로 보지 않고, 시험은 H2 + `ddl-auto: create-drop` 이라 Flyway 를 안 타므로
-- **운영 기동에서만 터진다.** `MigrationVersionTest` 가 그 구멍을 막는다.
--
-- 배포 순서: **develop 을 먼저 병합하고 배포한다.** 낮은 번호가 나중에 오면 Flyway 가
-- `Detected resolved migration not applied to database` 로 막는다. `outOfOrder=true` 로
-- 우회하지 않는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ★ 왜 이 값을 안 쓰기로 했나 (원본 근거)
--
-- 마이데이터 카드 업권 API 어디에도 할인·적립액 필드가 없다. 청구 추가정보(카드-005)는
-- 이용금액·수수료·할부 정보까지고, 국내 승인내역(카드-008)도 승인금액까지다. 그런데
-- 더미 생성기는 이 값을 만들어 넣었고(그것도 난수 실적구간에서 나온 값이다), 화면은
-- 결제마다 "−1,200원"을 초록색으로 그리고 있었다.
--
-- 실데이터로 넘어가면 그 화면이 통째로 사라진다. 지금 쓰지 않아야 그 위에 쌓이지 않는다.
-- 이 카드로 얼마를 아꼈는지는 카드 혜택 룰을 아는 쪽이 승인내역에서 계산할 몫이다.

