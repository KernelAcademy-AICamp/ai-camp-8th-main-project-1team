-- 사전 투표에서 **사람만 떼어낼 수 있게** 한다 (탈퇴·삭제요청 파기).
--
-- 한 표는 두 가지를 동시에 담고 있다 —
--   ① "이 가맹점은 카페/간식이다"  → 사전을 정하는 우리 자산. 지우면 안 된다.
--   ② "user 24 가 그렇게 봤다"      → 그 사람이 그 가맹점을 안다는 개인정보.
--
-- 그래서 파기 때 행을 지우지 않고 user_id 만 비운다. 표는 남아 집계에 계속 쓰이므로
-- 사전 판정이 흔들리지 않고, 사람과의 연결은 끊긴다. 행을 지우면 정당한 한 표가 사라져
-- 다음 투표 때 다수가 뒤집힐 수 있다 — 남의 사전이 남의 탈퇴로 나빠지면 안 된다.
--
-- 유일 제약 (business_number, merchant_name, user_id) 는 그대로 둔다. MySQL 은 유일 인덱스에서
-- NULL 을 서로 다른 값으로 보므로, 연결을 끊은 표가 여럿이어도 충돌하지 않는다. 그리고 그것이
-- 맞다 — 원래 서로 다른 사람들이 던진 표다.
--
-- 살아 있는 사람의 표에는 여전히 user_id 가 있어야 한다("사람당 하나"를 그것으로 센다).
-- 이 마이그레이션이 푸는 것은 **비울 수 있는가**이지 비워도 되는 규칙이 아니다.
ALTER TABLE merchant_category_vote
    MODIFY COLUMN user_id BIGINT NULL;
