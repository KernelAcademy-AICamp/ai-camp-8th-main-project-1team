-- 업종 축을 갈아탈 때 남은 옛 카테고리 셋을 정리한다 (2026-08-06)
--
-- 2026-08-04 에 업종 축을 국세청 6자리로 갈아타며(§10-K) 소비 카테고리가 15종으로 다시 짜였다.
-- 그때 새 이름을 넣기만 하고 **옛 이름을 지우지 않아** `category` 표에 셋이 남았다.
--
--   여가     → 취미/여가 로 대체됨
--   편의점   → 편의점/잡화 로 대체됨
--   온라인   → 대체할 것이 없다
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 지워야 하나 — 화면이 죽은 선택지를 보여준다
--
-- `GET /api/categories` 가 이 표를 그대로 내려주고, 분류를 고치는 화면이 그 목록으로 버튼을
-- 만든다. 지금 운영이 19개를 내려보내는데 셋은 **고르면 아무 데도 닿지 않는 이름**이다
-- (2026-08-06 실측). 사용자가 '편의점'과 '편의점/잡화' 중에 무엇을 골라야 하는지 알 수 없다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 옛 이름이 붙은 원장 행은 옮긴다 — 다만 '온라인'은 옮기지 않는다
--
-- `여가`·`편의점` 은 **이름만 바뀐 것**이라 새 이름으로 옮기면 뜻이 그대로다.
-- `온라인` 은 다르다 — 제공자가 넘기던 7대분류 시절의 값이고, 그때는 한 축이 업종과 소비종류를
-- 겸해서 **교통이 '온라인'에 들어가는 왜곡**이 있었다(`IndustryCategoryMapper` 주석). 무엇을
-- 산 것인지 알 수 없으므로 새 축의 어느 이름으로도 옮길 수 없다. `카테고리없음` 으로 내린다 —
-- **모르는 것을 아는 척하지 않는다.**
--
-- 지킴이 원장만 손댄다. `user_payment`·`consumption` 에는 이 셋이 하나도 없다(실측).

-- ── 이름만 바뀐 것 — 뜻을 유지한 채 옮긴다 ───────────────────────────────────
UPDATE guardian_transaction SET category = '취미/여가'   WHERE category = '여가';
UPDATE guardian_transaction SET category = '편의점/잡화' WHERE category = '편의점';

-- ── 뜻을 되살릴 수 없는 것 ───────────────────────────────────────────────────
UPDATE guardian_transaction SET category = '카테고리없음' WHERE category = '온라인';

-- ── 목록에서 뺀다 ────────────────────────────────────────────────────────────
-- `category.code` 를 참조하는 외래키는 `consumption.category_id`(대리키) 뿐이고 그쪽에는
-- 이 셋을 쓰는 행이 없다. 그래도 혹시 남아 있으면 지우지 않도록 조건을 건다 —
-- 마이그레이션이 데이터를 조용히 잃는 일은 없어야 한다.
DELETE FROM category
 WHERE code IN ('여가', '온라인', '편의점')
   AND NOT EXISTS (SELECT 1 FROM consumption c WHERE c.category_id = category.id);
