-- 사업자번호의 성격 — 한 사업인가, 여러 사업인가 (2026-08-05)
--
-- 사전은 (사업자번호, 가맹점 풀네임) 이 키인데, **번호만으로 붙이는 완화**가 하나 있다.
-- 한 사업자번호에 상호가 38,690종 붙은 곳이 있어서다(택시 — 표시명 뒤에 차량번호가 붙는다).
-- 정확일치만 쓰면 그런 가맹점은 사전이 영영 재사용되지 않고 행만 쌓인다.
--
-- 그런데 그 완화가 **닿으면 안 되는 번호**가 있다. 백화점 하나에 무인양품·러쉬·식품관이
-- 들어 있고, 울릉크루즈 한 번호에 여객선과 배 안의 GS25 가 붙는다. 번호로 묶는 순간 서로 다른
-- 가게가 한 분류로 오염되고, **사용자가 하나를 고치면 나머지까지 따라 바뀐다.**
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 번호만 보고는 못 가르나
--
-- "상호가 여럿인가"는 판정이 아니라 **신호**다. 택시도 KTX 도 상호가 여럿이지만 전부 같은
-- 사업이고, 거기서는 완화가 **꼭 필요하다**. 둘을 가르는 것은 *"그 상호들이 같은 것을 파는가"*
-- 이고, 그건 분류해 봐야 안다. 그래서 **관측하며 판정하고 그 결과를 여기 남긴다** —
-- 남기지 않으면 연동할 때마다 같은 것을 다시 묻게 되고, 그게 곧 재질문이다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 세 상태와 전이
--
--   UNKNOWN  상호가 여럿인 것을 봤지만 아직 판단 못 함        → 완화 **보류**
--   SINGLE   서로 다른 상호를 충분히 봤고 전부 같은 중분류      → 완화 **허용**
--   MULTI    중분류가 갈렸다                                → 완화 **금지**
--
--   UNKNOWN → SINGLE   서로 다른 상호 N종 이상이 전부 한 중분류로 모임 (N 은 설정)
--   UNKNOWN → MULTI    중분류가 갈림
--   SINGLE  → MULTI    사용자가 다른 중분류로 확정 → 그 순간 뒤집는다
--
-- **의심 쪽이 기본이다.** 두 오류의 무게가 다르기 때문이다 —
-- 복합인데 단일로 보면 **오염**이고 조용히 틀리지만, 단일인데 복합으로 보면 미분류가 늘 뿐이고
-- 그건 눈에 보이며 LLM·사용자가 채운다.
--
-- 상호가 **하나뿐인** 번호는 여기 오지 않는다. 완화해도 오염될 대상이 없다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 정적 목록과의 관계
--
-- `scripts/industry/복합사업자-사업자번호.tsv` 는 사람이 미리 적어 두는 목록이고, 이 표는
-- **관측으로 스스로 배우는** 자리다. 정적 목록에 있으면 첫 연동부터 막히고, 없어도 관측이
-- 쌓이면 여기서 잡힌다. 둘은 대체 관계가 아니다.

CREATE TABLE business_number_kind (
    business_number   VARCHAR(10)  NOT NULL,
    -- UNKNOWN / SINGLE / MULTI
    kind              VARCHAR(10)  NOT NULL,
    -- SINGLE 일 때 그 하나의 중분류. 판정 근거를 남겨 두면 왜 그렇게 정했는지 되짚을 수 있다.
    settled_category2 VARCHAR(30)  NULL,
    -- 지금까지 본 **서로 다른 가맹점명** 수. SINGLE 로 굳히는 근거이자, 왜 아직 UNKNOWN 인지의 답.
    merchant_names    INT          NOT NULL DEFAULT 0,
    -- 마지막으로 판정을 다시 계산한 시각. 관측이 늘면 갱신된다.
    observed_at       DATETIME(6)  NOT NULL,
    created_at        DATETIME(6)  NOT NULL,
    updated_at        DATETIME(6)  NOT NULL,
    PRIMARY KEY (business_number)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 조회는 언제나 번호 하나(PK)로 들어온다. 별도 인덱스가 필요 없다.
