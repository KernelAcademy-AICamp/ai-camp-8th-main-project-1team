-- 사전이 '왜 이 중분류인가'의 원재료를 함께 들게 한다 (2026-08-11)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 무엇이 버려지고 있었나
--
-- 국세청 업종코드는 **중분류로 바뀐 직후 사라진다.** 세 자리에서 그렇다.
--
--   ① scripts/industry/build_merchant_seed.py
--        codes(펴진 6자리 목록) → mids.pop() 한 문자열로 접힌다. 출력 TSV 에 코드 칸이 없다.
--   ② scripts/industry/load_merchant_seed.py
--        INSERT 가 (business_number, merchant_name, category2, source) 넉 칸만 쓴다.
--   ③ backend .../engine/IndustryCategoryMapper.midOfFineName
--        ntsByFineName 이 준 codes 는 만장일치 검사만 하고 없어지는 **지역변수**다.
--
-- 살아남는 곳은 user_payment.ksic_code 하나이고, 실 명세서 경로에서는 그마저 자리채움값
-- 642004 다(RealPersonImportService.UNKNOWN_INDUSTRY). 즉 사전은 답만 들고 근거를 안 든다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 보관해야 하나 ① — 표를 고쳐도 굳은 행이 안 따라온다
--
-- 중분류 배정의 단일 원천은 scripts/industry/nts-mid.tsv 다. 그런데 그 파일을 고쳐도
-- **이미 사전에 굳은 행은 옛 답을 그대로 들고 있다.** 실제로 그런 재배정을 한다 —
-- 백화점(521910)은 쇼핑, 대형 마트(521912)는 대형마트로 가르는 일이 그것이었다.
--
-- 다시 계산하려면 씨앗을 통째로 다시 빌드해야 하는데, **REGISTRY 로 들어온 행은 원천 CSV 에
-- 아예 없다.** 조회처의 답을 받아 그 자리에서 사전에 앉은 행이라 파일이 아니라 DB 에만 산다.
-- 원재료를 안 적어 두면 그 행은 영영 재계산할 수 없다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 보관해야 하나 ② — 이름만으로는 못 가르는 자리가 실재한다
--
-- 지금 남는 근거는 registry_industry(업종 **이름**, 80자 절단)뿐이다. 그런데 씨앗에 이런
-- 두 행이 있다(2026-08-11 실측).
--
--     2018513497  쇼핑      대규모점포     (521910 백화점)
--     5068518403  대형마트  대규모점포     (521912 대형 마트)
--
-- **이름이 같다.** 코드만이 둘을 가른다. 게다가 '대규모점포'는 세세분류 색인(ntsByFineName)에
-- 없어 이름에서 코드를 되찾는 길도 막혀 있다. 원재료는 원재료로 적어야 한다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 목록 전부인가 — 대표 하나로는 '모르겠다'를 재현할 수 없다
--
-- 한 업종명에 코드가 여럿 달린다(851201~851207, 851209, 851219 처럼 범위·복수). 살아 있는
-- 경로는 **그 코드들의 중분류가 만장일치일 때만** 답하고 갈리면 비운다(midOfFineName —
-- "억지로 고르는 대신 비워서 LLM 으로 내려보낸다"). 대표 코드 하나만 적으면 재계산이 그
-- 판단을 못 한다. 오늘 갈리는 곳이 0곳인 것은 *현재 표 기준*이고, 이 칸이 필요해지는 순간이
-- 바로 표를 고치는 순간이며, 표를 고치는 것이 갈림을 만든다.
--
-- 원본 스펙 문자열(`851201~851207, 851209`)을 그대로 담지 않는 이유도 같은 결이다. 그러면
-- expand()(build_merchant_seed.py)의 **자바 쌍둥이**가 필요해지는데, 이 저장소는 그 덫을 이미
-- 한 번 파 두고 경고문을 붙여 놨다(IndustryCategoryMapper.normalizeFineName — "글자 하나까지
-- 같아야 한다. 한쪽만 고치면 색인은 멀쩡한데 아무것도 안 붙는 조용한 실패가 난다").
-- 펴서 담으면 재계산이 쉼표로 자르는 것뿐이라 **갈라질 규칙 자체가 없다.**
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 비어 있는 것도 뜻이다
--
--   값이 있다  → 이 행의 중분류는 **표에서 유도**됐다 (USER_CSV · REGISTRY)
--   NULL       → 표에서 나오지 않았다
--                  · USER_CONFIRMED             사람이 정했다. 없는 것이 정상이다.
--                  · LLM_GUESS·ATTEMPTED·UNRESOLVED   애초에 유도가 없다.
--
-- 그래서 재계산 대상이 `source IN ('USER_CSV','REGISTRY')` 하나로 떨어진다. 사람이 화면에서
-- 확정하면 이 칸을 **지운다** — 지금 값과 무관한 근거가 남으면, 설명가능성을 위해 만든 칸이
-- 오해를 만드는 칸이 된다. 잃는 것은 없다(registry_industry 가 그대로 남는다).
--
-- 추정층(LLM_GUESS)에는 적지 않는다. 모델이 답한 업종 이름을 표로 옮겨 코드를 역산하는 것은
-- 기술적으로 되지만, 그렇게 적으면 이 칸이 "표에서 유도"와 "모델의 말을 표로 옮김"을 한꺼번에
-- 담아 **읽을 수 없는 칸**이 된다. V27 이 주소 실패를 lookup_attempts 에 안 섞은 것과 같은
-- 이유다 — 한 칸에 둘을 섞으면 둘 다 잃는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 형식과 길이
--
-- 6자리 0채움 · ASCII 쉼표 · 공백 없음 · 오름차순 · 중복 없음 · 끝 쉼표 없음.
-- **쓰기는 이 형식으로, 읽기는 관대하게**(쉼표로 자르고 trim, 빈 값은 버린다).
--
-- 빈 문자열은 쓰지 않는다 — business_number 가 '' 인 것은 UNIQUE 가 NULL 끼리 다르다고 봐서
-- 같은 가맹점이 여러 번 쌓이기 때문이고(V15), 이 칸에는 그 사정이 없다. 없으면 NULL 이다.
--
-- 120 은 실측에서 왔다(2026-08-11). 한 세세분류 이름에 달린 코드는 원천 1,542개를 통틀어
-- 최대 **9개**이고(그외기타분류안된상품전문소매업), 이으면 **62자**다. 120 이면 17개까지 담아
-- 관측 최악의 두 배이고, 그리고 이 표가 이미 쓰는 폭이라(merchant_name VARCHAR(120), V15)
-- 새 숫자를 하나 더 만들지 않는다.
--
-- 문자셋을 따로 주지 않는다. 값이 숫자와 쉼표뿐이라 ascii 가 더 정확해 보이지만, 이 표의
-- 다른 칸은 utf8mb4 이고(V26 address) 섞으면 나중에 비교·조인에서 collation 이 부딪힌다
-- (V23 이 브랜드에서 정리한 종류의 문제다).
--
-- 인덱스는 두지 않는다. 이 칸을 술어로 쓰는 곳은 재계산 대상 고르기 하나뿐인데, 그것은
-- source 로 고르고 사전은 수백 행이라 어차피 전부 읽는다. 대부분 NULL 인 문자열 칸에
-- 인덱스를 붙이는 것은 값을 못 한다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 새 파일로 낸다
--
-- V15·V21·V22·V26·V27 은 이미 운영에 적용됐고 Flyway 가 파일 내용 전체로 체크섬을 계산하므로
-- 주석 한 글자도 고치지 않는다(CLAUDE.md 규칙 3). **V28 은 이미 쓰였다**(guardian_tx_source_index,
-- 2026-08-11) — 같은 버전 두 파일이면 기동이 막힌다. 그래서 V29 다.
--
-- 여기에 UPDATE 로 값을 박지 않는다. 되돌릴 수 없고(규칙 3), 실제 결제처의 사업자번호를
-- 저장소에 커밋하는 일이 된다(load_merchant_seed.py 머리말 · check_no_real_numbers.py).
-- 채우는 것은 씨앗 재적재(USER_CSV)와 registry_industry 역산(REGISTRY)이 한다.

