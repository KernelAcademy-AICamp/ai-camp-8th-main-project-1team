-- 사전이 가맹점 주소도 기억한다 (2026-08-08)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 무엇이 안 되고 있었나
--
-- 화면에서 사업자번호를 누르면 주소가 뜨게 되어 있는데, **실사용자에게는 거의 안 뜬다.**
-- 조회처가 제공자(backend-mydata)인데 거기에는 생성기가 만든 번호만 있기 때문이다.
--
--     실사용자 결제의 사업자번호      132종
--     그중 제공자가 아는 것             7종  (5%)
--
-- 7종이 나오는 이유는 그 번호가 더미 결제에도 쓰였기 때문이다 — 생성기가 실재하는 번호를
-- 골라 썼다. 그리고 그때 돌아오는 주소는 **합성이 아니라 공개 상권/POI 에서 온 실물**이다
-- (계획서 W1-0 ①: "동선은 공개 상권/POI 데이터(주소·좌표·업종)에 앵커링한다").
-- 즉 지금 보이는 7종은 옳고, 문제는 나머지 125종이 안 보인다는 것뿐이다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 사전에 두나 — 조회를 한 번도 더 안 하기 위해서다
--
-- 등록 업종 조회(②-b)는 사업자번호로 등록처의 문서를 받아 **업종 이름을 정규식으로 뽑는다.**
-- 그 문서에는 주소도 함께 들어 있다. 즉 **이미 손에 있는 것을 버리고 있었다.**
--
-- 같은 문서에서 주소도 뽑아 여기에 적으면 바깥 호출이 한 번도 안 는다. 그리고 한 번 적으면
-- 다음부터는 조회 없이 답한다 — `registry_industry` 를 사전에 남기는 것과 같은 이치다(V21).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 merchant_category 인가
--
-- 주소는 **사업자번호에 붙는 성질**이고, 사전의 키가 (사업자번호, 상호)라 그대로 얹힌다.
-- 브랜드(`merchant_brand`)와 달리 별도 표가 필요 없다 — 브랜드는 번호가 없는 해외 결제에도
-- 붙어야 해서 이름을 키로 따로 뒀지만, 주소는 번호가 없으면 애초에 조회할 수가 없다.
--
-- 길이 200 은 지번+도로명이 함께 오는 형태를 담기 위한 것이다.
-- (예: `경기 용인시 처인구 포곡읍 전대리 310 (에버랜드로 199)` — 45자)

ALTER TABLE merchant_category
  ADD COLUMN address VARCHAR(200) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NULL;
