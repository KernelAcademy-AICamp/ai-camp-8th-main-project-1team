-- 도감 마일스톤 지급 이력 (개편안 s-collection).
--
-- 왜 컬럼이 필요한가. 지급 여부를 '소유 종수 >= 기준'으로만 판정했더니 두 방향으로 틀렸다.
--   ① 21종을 모은 사용자는 세 마일스톤이 전부 '받음'으로 표시돼 **한 번도 못 받고 끝난다**
--      (화면의 청구 버튼이 뜨지 않는다). 실제로 면제권 0장인 채 '받음'이 찍혔다.
--   ② 반대로 청구 API는 종수만 보므로 호출할수록 **계속 지급된다**.
-- 종수는 "열렸는가"만 말한다. "받았는가"는 따로 기록해야 한다.
--
-- CSV로 두는 이유: 마일스톤은 세 개뿐이고 앞으로도 손에 꼽는다. 이력 테이블을 하나 더 만들면
-- 조회마다 조인이 붙는데, 얻는 것은 없다.
