-- 사전 한 행이 그 가맹점의 **상태**를 들게 한다 (2026-08-07)
--
-- 지금까지 사전은 "분류를 알아낸 가맹점"만 담았다. 그래서 못 알아낸 가맹점에 대해서는
-- 아무 기록도 남지 않았고, 연동할 때마다 **같은 일을 처음부터 다시 했다** —
-- 같은 사업자번호를 다시 조회하고, 같은 상호를 LLM 에 다시 물었다.
--
-- 그리고 '카테고리없음' 하나가 서로 다른 두 가지를 같이 담고 있었다:
--
--     아직 안 물어봤다        → 물어봐야 한다
--     다 물어봤는데 모른다    → 더 물어도 소용없다
--
-- 이 둘을 같은 값으로 두면 뒤엣것을 영원히 다시 처리한다. 종결을 적을 자리가 필요하다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 무엇을 세는가
--
--   lookup_attempts    바깥 조회처(사업자등록번호 → 등록 업종)에 물어본 횟수
--   registry_industry  그 답. **못 붙였어도 남긴다** — 버리면 다음 연동에 또 조회한다.
--                      그리고 이 이름은 LLM 에게 줄 근거이기도 하다("등록 업종은 이렇다").
--   llm_attempts       LLM 에 물었는데 답이 없었던 횟수
--   last_attempt_at    마지막 시도 시각. 통로가 죽었는지 보는 단서다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 종결 기준이 LLM 3회인가 (조회 실패가 아니라)
--
-- 조회처가 모른다고 LLM 도 모르는 것이 아니다. 실측에서 조회는 답했지만 그 업종이
-- 법인 주업종이라 소비를 설명하지 못한 경우가 많았고(아파트 건설업으로 등록된 회사의
-- 결제가 주차비였다), 그런 가맹점이야말로 상호를 보는 LLM 이 잘 푼다. 반대로 LLM 은
-- 다시 물으면 답이 달라질 수 있어 한두 번으로 단정할 수 없다. 그래서 **세 번**이다
-- (사용자 확인 2026-08-07). 그만큼 묻고도 안 되면 더 묻는 것은 비용만 든다.
--
-- 종결되면 category2 가 '기타'가 되고 source 가 UNRESOLVED 가 된다. 영구가 아니다 —
-- 사람이 화면에서 고치면 USER_CONFIRMED 가 덮고 confirmed_by·updated_at 에 남는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 키는 그대로 (사업자번호, 가맹점 풀네임)다
--
-- 번호만으로 세면 안 된다. PG 를 거친 결제는 한 번호에 서로 다른 가게가 붙고, 복합
-- 사업자는 한 번호에 성격이 다른 가게가 붙는다. 시도 횟수도 분류와 **같은 키**로 세야
-- '교보문고를 세 번 물었다'와 '그 PG 를 세 번 물었다'가 섞이지 않는다.

ALTER TABLE merchant_category ADD COLUMN registry_industry VARCHAR(80) NULL;
ALTER TABLE merchant_category ADD COLUMN lookup_attempts INT NOT NULL DEFAULT 0;
ALTER TABLE merchant_category ADD COLUMN llm_attempts INT NOT NULL DEFAULT 0;
