-- 저축상품 우대조건 라벨 표 — M6(실수령 금리 3분기)이 읽을 그릇 (2026-08-11)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 무엇이 없어서 만드나
--
-- FP-01 매칭 규칙(M1~M10)은 다 서 있는데 M6이 **모든 상품이 같은 우대조건을 요구한다**고
-- 가정하고 있었다(`SavingsCompareService.ASSUMED_CONDITIONS` = 카드 실적 + 급여이체).
--
-- 2026-08-11 금감원 응답 실측이 그 가정을 반증했다 (적금 58건 · 정기예금 38건):
--
--     급여이체 언급        7/58 (12%)
--     카드 실적 언급       7/58 (12%)
--     둘 중 하나라도      10/58 (17%)
--     **둘 다 없음        48/58 (83%)**   ← 여기가 통째로 틀린 판정을 받고 있었다
--     최빈은 자동이체     24/58 (41%)     ← 우리가 판정할 수 없는 축
--
-- 결과적으로 M6은 거의 모든 상품을 같은 기본금리로 떨어뜨려, 그룹 내 정렬이 사실상
-- 기본금리 순으로 붕괴해 있었다. 상품마다 조건을 읽어야 규칙이 산다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 "상품"이 아니라 "라벨"을 저장하나
--
-- 금융상품(예적금)은 **DB에 쌓지 않는다** — 금감원 API 실시간 조회다(용어사전 §9).
-- 여기 쌓는 것은 상품이 아니라 자연어 공시를 구조로 옮긴 **라벨**이고, 목적은 LLM 호출을
-- 줄이는 캐시다. 같은 이유로 이미 존재하는 `product_eligibility`(V8, 가입 자격)와 짝이며
-- 구조를 일부러 똑같이 맞췄다.
--
--     product_eligibility   join_member  → (min_age, max_age, special_status)
--     product_preferential  spcl_cnd     → 조건 종류 목록 + 당행 한정 여부   ← 이 파일
--
-- 수명 관리도 같다: 시간 만료가 아니라 **공시 문구의 해시**로 본다. 금리가 매일 바뀌어도
-- 우대조건 문구가 그대로면 재판정하지 않는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- conditions 칸을 왜 표로 안 쪼갰나
--
-- 조건은 상품당 대여섯 개를 넘지 않고 **통째로만** 읽고 쓴다(부분 갱신이 없다). 조인해서
-- 걸러 볼 값도 없다. 표를 하나 더 만들면 라벨 한 건을 쓸 때마다 delete+insert가 되고,
-- 그 대가로 얻는 것이 없다.
--
--     'CARD_PERFORMANCE@OWN,SALARY_TRANSFER@ANY,MARKETING_CONSENT@ANY'
--      └ 종류         └ 당행 한정이면 OWN — 그 금융사 것으로 좁혀 판정한다(M6 ④)
--
-- **빈 문자열은 '요구 조건이 없다'이고, 행이 없는 것과 다르다.** 실측에 `spcl_cnd`가
-- `없음`인 상품이 3건 있는데(`퍼스트가계적금`), 그런 상품은 채울 조건이 없으니 곧바로
-- 최고금리다. 행이 없으면 아직 라벨링을 안 한 것이라 기본금리 + '확인 불가'로 간다.
-- 이 둘을 뭉개면 우대조건이 없는 상품에 '미충족: 카드 실적'이라고 **없는 조건을 지어내
-- 말하게 된다** (개정 전 코드가 실제로 그랬다).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 정본: `reference/기획/04_스펙/07_취향분석및추천_Agent_설계.md` §4.5 M6
-- 실측 재현: `scripts/collect-savings/inspect_fss.py`

create table product_preferential (
    id bigint not null auto_increment,
    prdt_key varchar(80) not null,
    spcl_cnd_hash varchar(64) not null,
    -- 빈 문자열 = 요구 조건 없음. null 이 아니다(행 없음과 구분해야 한다).
    conditions varchar(500) not null,
    source varchar(10) not null,
    labeled_at datetime(6) not null,
    primary key (id)
) engine=InnoDB;

-- 상품 식별키는 하나만 존재한다(금리가 바뀌어도 유지되는 `금융회사코드:상품코드`).
alter table product_preferential add constraint uk_product_preferential_prdt_key unique (prdt_key);
