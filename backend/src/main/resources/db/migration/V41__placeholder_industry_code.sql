-- 자리표 업종코드를 `642004` 에서 `000000` 으로 옮긴다.
--
-- **자리표가 진짜 코드여서는 안 된다.** 642004 는 국세청이 실제로 발급한 코드
-- (포털 및 기타 인터넷 정보 매개 서비스업)라, 진짜 그 업종인 가맹점과 "모른다"는 표시가
-- 글자로 구별되지 않는다. 이 저장소는 사업자번호에 대해 이미 같은 규칙을 세워 두었다 —
-- `scripts/industry/check_no_real_numbers.py`:
--
--     자리표가 필요하면 **`0` 으로 시작하는 번호**를 쓴다. 국세청은 그런 번호를
--     발급하지 않아 진짜와 겹치지 않는다.
--
-- 업종코드에는 그 규칙을 안 지키고 있었다. 여기서 맞춘다.
--
-- **왜 자리표가 필요한가** — 카드 명세서에는 업종코드가 없다. 제공자가 안 주므로 적재기가
-- 넣을 값이 없는데 스키마가 NOT NULL 이다. 비워 둘 수 없으니 "모른다"를 적는다.
--
-- 옮기는 양은 결제 1,792행 · 원장 1,653행이다(2026-08-25 실측). 생성 데이터(1,100만 건)는
-- 제공자 DB에 있어 여기 없다 — 그쪽은 코드가 다음 재생성 때 바뀐다.

UPDATE user_payment    SET ksic_code            = '000000' WHERE ksic_code            = '642004';
UPDATE spending_ledger SET nts_industry_code    = '000000' WHERE nts_industry_code    = '642004';
