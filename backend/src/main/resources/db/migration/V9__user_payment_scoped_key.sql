-- V9 — 결제 적재 키를 계정별로 분리한다.
--
-- 무엇이 문제였나: user_payment의 PK가 **제공자가 준 결제 id**였다. 그러면 앱 사용자가 달라도
-- 같은 신원(CI)이면 행이 하나뿐이라, 두 번째 계정이 연동하는 순간 save()가 기존 행의 user_id를
-- 덮어써 먼저 연동한 사람의 화면이 통째로 빈다. 운영에서 실제로 재현했다 —
-- 한 계정의 결제 2,404건이 다른 계정으로 옮겨갔고, 앞 계정에는 consumption만 남아 어긋났다.
--
-- 데모 신원은 5개뿐이고 보는 사람마다 브라우저가 달라 앱 계정이 따로 생긴다.
-- 두 사람이 같은 페르소나를 고르는 것은 예외가 아니라 기본값이다.
--
-- 왜 이 UPDATE가 필요한가: 코드만 바꾸면 기존 행은 옛 키(제공자 id)로 남는다. 증분 동기화는
-- 새 키로 존재 여부를 확인하므로 **이미 적재된 결제를 못 찾아 같은 건을 다시 쌓는다.**
-- 여기서 한 번에 옮겨 두 규칙이 갈라지지 않게 한다.
--
-- 컬럼은 varchar(40)이고 제공자 id는 22자 안팎이라 접두사를 붙여도 들어간다.
-- 이미 옮긴 행은 건드리지 않으므로 다시 실행해도 결과가 같다(정규식 가드).

UPDATE user_payment
   SET payment_id = CONCAT(user_id, ':', payment_id)
 WHERE payment_id NOT REGEXP '^[0-9]+:';
