-- **소비내역에 적을 이름을 기록으로 남긴다.**
--
-- 실사용자 결제 2,136건 중 **619건(29%)**이 PG 사업자번호로 찍힌다(2026-08-26 운영 실측).
-- 그 상호는 `토스페이_일반-(주)비바리퍼블리카`·`정기결제_K-주식회사 퍼플룰러` 처럼
-- **결제 경로가 이름을 밀어낸 꼴**이라 목록이 읽히지 않는다.
--
-- 표시명은 **원문의 부분집합**이다 — 지어내지 않는다. 우리가 하는 일은 실제 결제처를
-- 알아내는 것이 아니라 **확실히 버려도 되는 것만 버리는 것**이고, 그래서 틀릴 수가 없다.
--
-- **왜 화면에서 계산하지 않고 적어 두나.** 표기 1,200여 개를 훑는 일이라 목록을 열 때마다
-- 하면 같은 상호를 수백 번 다시 푼다. 그리고 이것은 렌더링 결과가 아니라 *"이 가맹점명은
-- 이렇게 읽는다"* 는 **사실**이다 — category2·ksic_code 를 결제 행에 적어 둔 것과 같은 이유다.
--
--   display_name          화면에 적을 이름
--   display_name_source   무엇으로 정했나 — 화면이 배지·펼침을 가르는 근거다
--                           BRAND        표기표가 확정한 브랜드
--                           RESIDUE      PG·업태를 걷어내고 원문에 남은 상호
--                           AGENCY_ONLY  걷어내니 아무것도 안 남았다(결제 경로만 안다)
--                           RAW          PG 가 안 섞인 보통의 상호
--
-- 원문(`merchant_name`)은 **그대로 둔다.** 어느 지점인지가 사라지면 안 되고, 검색은 원문과
-- 표시명 양쪽을 본다.

ALTER TABLE user_payment
    ADD COLUMN display_name VARCHAR(60) NULL COMMENT '소비내역에 적을 이름 — 원문의 부분집합이다',
    ADD COLUMN display_name_source VARCHAR(16) NULL COMMENT 'BRAND·RESIDUE·AGENCY_ONLY·RAW',
    ADD COLUMN via_agency VARCHAR(40) NULL COMMENT '거쳐 간 결제대행사. 사업자번호가 알려 준 사실이다';
