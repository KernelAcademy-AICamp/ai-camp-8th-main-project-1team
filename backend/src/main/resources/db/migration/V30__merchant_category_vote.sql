-- 사람의 확정을 한 표로 세고, 전역은 다수가 정한다 (2026-08-11)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 무엇이 잘못 돌고 있었나
--
-- `MerchantCategoryService.confirm` 은 **아무 조건 없이 덮었다.**
--
--     A 가 '배달의민족'을 식비로 확정   → 사전: 식비
--     B 가 같은 곳을 쇼핑으로 확정      → 사전: 쇼핑   (A 의 판단은 흔적 없이 사라진다)
--
-- 표도 문턱도 없이 **마지막에 누른 사람이 이긴다.** 되돌릴 기록도 없었다 — `confirmed_by` 에
-- 남는 것은 마지막 사람 하나이고, 그 전에 무엇이었는지는 어디에도 없다. 사람은 오분류하고
-- 착각하는데(사용자 지적 2026-08-11), 사전은 **전역 자산**이라 한 번의 실수가 모두에게 간다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 이 프로젝트는 한 층 아래에서 이미 같은 원칙을 세웠다
--
-- `business_number_kind`(V16) 가 그것이다 —
--
--     "SINGLE 은 상호 5종을 관측해 굳는데 MULTI 는 한 번의 교정으로 뒤집힌다면, 사용자가
--      택시 한 건을 실수로 잘못 고치는 순간 그 뒤의 수만 건이 전부 따로 기록된다.
--      **한 번의 반대는 그 상호만의 예외로 둔다.**"
--
-- 그 원칙을 한 층 위, `category2` 자체에 올린 것이 이 표다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 절반은 이미 있었다 — 개인층
--
-- 새로 만드는 것은 **전역층의 표뿐**이다. "본인에게만 적용"은 이미 돌고 있다:
--
--     user_payment.category2_source = 'USER'   ← 사람이 고친 결제
--     그 값을 사전이 덮지 않는다                ← MyDataLinkService.applyResolved · alsoFixed 루프
--
-- 그래서 표에서 져도 **자기 결제는 자기 답을 유지한다.** 이 마이그레이션과 함께 `alsoFixed`
-- 루프도 고친다 — 지금은 사전의 답을 본인의 다른 결제에 밀어 넣어서, 내 표가 지면 **남의
-- 다수결이 내 결제를 덮는다.** 본인의 표를 사전보다 먼저 본다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 표는 사람당 하나다
--
-- UNIQUE (business_number, merchant_name, user_id).
--
-- **결제당으로 세면 안 된다.** 티머니 17건을 고친 사람이 17표를 던지게 되고, 그러면 결제가
-- 많은 사람이 곧 다수가 된다 — 세려던 것은 "몇 명이 그렇게 보는가"이지 "몇 건을 눌렀는가"가
-- 아니다. 다시 확정하면 자기 표가 **바뀐다**(늘지 않는다). 실수를 되돌리면 반대 증거가
-- 사라지는 것이 `business_number_kind` 와 같은 이치다.
--
-- 키는 사전과 **같은 규칙**이다 — PG 번호는 지우고 이름으로 본다(V15 · §13-12). 두 곳의 키가
-- 갈리면 표는 쌓이는데 사전은 못 찾는, 오류 없는 실패가 난다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 문턱: 단순 다수결, 동률이면 현재 유지
--
--     쇼핑 2 · 식비 1   → 쇼핑
--     쇼핑 2 · 식비 2   → **아무것도 안 바꾼다** (사전 행을 그대로 둔다)
--     쇼핑 3 · 식비 2   → 쇼핑
--
-- 표가 이미 사람당 하나라 다수결 자체가 비례적이다 — 뒤집는 데 별도 비율을 더 요구하지 않는다
-- (`business_number_kind` 는 관측 단위가 '상호'라 비율이 필요했다. 여기는 '사람'이다).
--
-- 동률에서 현재를 유지하는 것이 요점이다. 갈렸다는 것은 **그 가맹점이 사람마다 다르게 보인다**는
-- 뜻이고(배달의민족 — 등록은 통신판매업이라 쇼핑, 쓴 돈은 밥값), 그럴 때 억지로 고르면 진 쪽의
-- 전역 화면이 이유 없이 흔들린다. 모를 때는 보류가 기본이다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 전제를 하나 양보한다
--
-- 사전의 전제는 *"사람에 따라 달라지지 않는 사실"* 이었다(`MerchantCategory` 클래스 주석).
-- 투표는 그것을 양보한다 — 사람마다 다르게 볼 수 있음을 인정하는 장치이기 때문이다.
-- 양보하는 대신 **개인층이 정답이고 전역은 기본값**이라는 서열을 분명히 한다:
--
--     내 결제        내 표            (category2_source='USER' 가 지킨다)
--     처음 보는 결제  전역 다수결       (사전이 준다)
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 사전 행을 FK 로 걸지 않는다
--
-- 자연키(번호, 상호)로 잡는다. 사전 행은 재연동·재적재로 지워졌다 다시 생길 수 있는데
-- (`linkCardCompanies` 가 결제를 지우고 다시 만든다), 표는 **사람의 판단**이라 그때 같이
-- 날아가면 안 된다. 자연키로 두면 행이 다시 생겨도 표가 그대로 붙는다.
--
-- 새 파일로 낸다 — V29 까지는 이미 있다(CLAUDE.md 규칙 3).

CREATE TABLE merchant_category_vote (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    -- 사전과 같은 키다. PG 번호는 지워져 빈 문자열로 들어온다.
    business_number VARCHAR(10)  NOT NULL DEFAULT '',
    merchant_name   VARCHAR(120) NOT NULL,
    user_id         BIGINT       NOT NULL,
    category2       VARCHAR(30)  NOT NULL,
    created_at      DATETIME(6)  NOT NULL,
    updated_at      DATETIME(6)  NOT NULL,
    PRIMARY KEY (id),
    -- **사람당 한 표.** 다시 확정하면 이 행이 바뀐다(늘지 않는다).
    CONSTRAINT uq_merchant_category_vote UNIQUE (business_number, merchant_name, user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 집계는 언제나 (번호, 상호) 한 가맹점 단위로 전부 읽는다. 유일키의 앞 두 칸이 그 접두사라
-- 따로 인덱스를 만들지 않아도 그 색인이 쓰인다.
