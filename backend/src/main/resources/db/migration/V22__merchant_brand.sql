-- 가맹점명에서 **브랜드**를 뽑아 둔다 (2026-08-07)
--
-- 실 명세서의 가맹점명은 지점까지 붙어 있다 — `GS25 강남역점` · `GS25 포스텍학술정보관점` ·
-- `스타벅스 포항공대점`. 지금은 이것들을 **각각 따로** 물어보고 각각 따로 사전에 쌓는다.
-- 같은 브랜드인 줄 모르기 때문이다.
--
-- 브랜드를 알면 두 가지가 된다.
--   ① **질문이 준다.** 브랜드 하나를 알면 그 브랜드의 새 지점은 안 물어도 된다.
--   ② **분류를 물려준다.** `GS25 강남역점`이 편의점이면 `GS25 역삼점`도 편의점이다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 표를 둘로 나누나
--
--   merchant_category.brand   **확정된** 가맹점의 브랜드. 사전과 한 몸이다.
--   merchant_brand            아직 사전에 못 들어간 가맹점의 브랜드. **대기 장소**다.
--
-- 사전은 "이 점포의 업종이 무엇인가"에 대한 확정된 답만 담는다는 약속이 있다. 브랜드만
-- 알아낸 가맹점을 그 약속 안으로 밀어 넣으면 분류가 없는 행이 사전에 앉는다. 그래서
-- 따로 두고, **그 가맹점이 사전에 들어가는 순간 브랜드를 옮기고 여기서 지운다.**
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 키가 가맹점명인 이유
--
-- 브랜드는 **이름에서 나온다.** 사업자번호는 브랜드를 말해 주지 않는다 — PG 를 거치면 번호가
-- 남의 것이고, 프랜차이즈는 지점마다 번호가 다르다. 반대로 이름은 언제나 있다(번호 없는
-- 해외 결제에도). 그래서 여기만은 번호를 키로 쓰지 않는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 무료 통로가 채운다
--
-- 브랜드 추출은 가맹점 **하나씩** 묻는다. 묶어 물으면 모델이 지점명을 흘리거나 엉뚱한 것을
-- 브랜드로 잡는데, 이 질문은 프롬프트가 짧아(업종 목록이 필요 없다) 하나씩 물어도 싸다.
-- 그리고 부르는 곳이 무료 통로라 회수 제한을 둘 이유가 없다.

CREATE TABLE merchant_brand (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    merchant_name VARCHAR(120) NOT NULL,
    brand         VARCHAR(60)  NOT NULL,
    source        VARCHAR(20)  NOT NULL,
    created_at    DATETIME     NOT NULL,
    updated_at    DATETIME     NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_merchant_brand_name (merchant_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE merchant_category ADD COLUMN brand VARCHAR(60) NULL;
