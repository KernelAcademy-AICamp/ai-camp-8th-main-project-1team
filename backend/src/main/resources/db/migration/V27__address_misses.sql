--
-- V26 이 붙인 주소 백필(`MyDataLinkService.fillMissingAddresses`)은 "주소가 아직 없는 행"을
-- 회차마다 골라 조회처에 묻는다. 그런데 **답이 없는 것이 정상인 번호가 있다.**
--
--     1048526046  롯데쇼핑(주) 롯데아울렛 서울역점   조회는 되는데 주소칸이 비어 있다
--     4141402029                                     사업자 자체가 안 나온다
--     7242601615                                     같음
--
-- 이런 행은 성공이 영영 안 오는데 "물어봤다"를 안 남기니 다음 회차에 다시 뽑힌다. 실측
-- (2026-08-08 운영): **7곳이 5분마다 = 하루 2,016회**가 남의 서버로 헛나갔다. 채워진 곳은 0 이다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 `lookup_attempts` 를 같이 쓰지 않나 — 끝나는 조건이 다르다
--
-- 업종 조회는 답을 받으면 `registry_industry` 가 차고, 그 뒤로는 조회 대상에서 저절로 빠진다.
-- 즉 **성공이 종료 조건**이라 실패를 셀 필요가 없었다.
--
-- 주소는 성공이 안 오는 번호가 있으므로 **실패를 세야만** 멎는다. 한 칸에 둘을 섞으면 업종
-- 조회의 실패가 주소를 막고 그 반대도 되어, 둘 중 하나가 되는 번호에서 다른 하나를 잃는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 3회에서 멎는다
--
-- `MerchantCategory.GIVE_UP_AFTER`(=3)를 그대로 쓴다. LLM 질문과 같은 기준이다 — 한 번은
-- 그때 조회처가 잠깐 이상했을 수 있고, 세 번이면 그 번호에 주소가 없는 것이다.
--
-- **못 물어본 것에는 안 적는다.** PG·복합 번호는 `IndustryLookupService.askable` 이 먼저
-- 막으므로 여기까지 오지 않는다. 물어보지 않은 것에 "물어봤다"를 적는 것은 기록이 아니라
-- 잡음이다(V24 에서 같은 이유로 관측에 실사용자 관문을 뒀다).
--
-- 멎어도 잃는 것은 **주소 하나뿐**이다. 업종 조회·분류·브랜드는 이 값을 보지 않는다.

