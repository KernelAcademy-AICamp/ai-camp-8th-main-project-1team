-- 지킴이 털색 — 고른 색을 기억한다 (2026-08-06)
--
-- 프로토타입_0806 이 마이룸 꾸미기에 '캐릭터' 탭을 더했다. 털색이 다섯이고(크림·그레이·치즈·
-- 초코·삼색이) 그중 삼색이만 상점에서 300P 에 산다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 '가진 것'과 따로 두나
--
-- 산 물건은 `guardian_room_object` 에 쌓인다. 그런데 털색은 **여러 개를 함께 놓는 것이 아니라
-- 언제나 하나만 고르는 것**이다. 게다가 크림·그레이·치즈·초코는 <b>사지 않아도 고를 수 있다</b> —
-- 보유 목록에 없으니 거기서는 "지금 무슨 색인가"를 답할 수 없다.
--
-- 그래서 보유(room_object)와 선택(여기)을 가른다. 삼색이를 샀다고 늘 삼색이로 다녀야 하는 것도
-- 아니다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 기본값
--
-- `cat` 은 기본 크림색이다. 기존 행이 있으므로 NOT NULL 에 기본값을 준다 — 값이 없다고
-- 캐릭터가 사라지면 안 된다. 엔티티도 빈 값을 `cat` 으로 읽어 두 겹으로 막는다.

ALTER TABLE guardian_items
    ADD COLUMN cat_skin VARCHAR(20) NOT NULL DEFAULT 'cat';
