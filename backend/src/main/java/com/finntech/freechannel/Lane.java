package com.finntech.freechannel;

/**
 * 무료 통로에 낼 일의 <b>차선</b> — 값이 곧 우선순위다(위가 먼저).
 *
 * <p><b>기본값을 두지 않는다.</b> {@link FreeChannelQueue#submit} 에 이 값이 <b>필수 인자</b>인
 * 이유가 그것이다. 생략할 수 있는 오버로드를 하나라도 두면 새 코드가 전부 그리로 가고,
 * 그러면 "이 일이 급한가"를 아무도 안 묻게 된다.
 *
 * <p><b>고르는 물음은 하나다</b> — <i>"이 일을 안 하면 사용자가 지금 나쁜 것을 보는가."</i>
 * 차선 이름을 큐 번호(1차·2차)가 아니라 이렇게 지은 이유는, 새 코드를 쓰는 사람에게 우리 큐
 * 사정은 알 바가 아니고 <b>자기 화면이 어떻게 되는가</b>만이 판단 근거이기 때문이다.
 *
 * <p><b>왜 실사용자·더미가 차선에 섞여 있나.</b> 무료 통로라 더미를 돌려도 돈은 안 든다. 그런데
 * 연동 사용자 13명 중 12명이 더미라, 섞어 두면 예산의 대부분을 더미가 쓴다. 그렇다고 아예
 * 막으면 데모 화면이 고정 템플릿만 보인다. 그래서 <b>맨 뒤에 둔다</b> — 실사용자 것이 다
 * 끝났을 때만 돌고, 위가 비면 놀리지 않고 돈다.
 */
public enum Lane {

    /**
     * <b>실사용자가 지금 나쁜 것을 본다.</b> 문장이 아예 없어 고정 템플릿이 뜨는 자리.
     *
     * <p>"낡음"과 "없음"은 사용자가 보는 것이 다르다 — 낡으면 어제의 멀쩡한 문장이고, 없으면
     * 기계 같은 템플릿이다. 그래서 이 둘만은 차선을 가른다.
     */
    USER_NOW,

    /**
     * <b>실사용자의 갱신.</b> 어제 문장이 보이므로 미뤄도 화면이 안 나빠진다.
     */
    USER_REFRESH,

    /**
     * <b>실사용자의 뒷일.</b> 화면에 걸려 있지 않은 것 — 브랜드 라벨링이 여기다.
     *
     * <p>{@link #USER_REFRESH} 보다 뒤인 이유는 그쪽은 사용자가 볼 문장이고 이쪽은 아니기
     * 때문이다. 다만 더미보다는 앞이다 — 실사용자의 데이터이기 때문이다.
     */
    USER_BACKGROUND,

    /**
     * <b>더미.</b> 위가 다 비었을 때만 돈다.
     *
     * <p>돈이 안 드는데도 뒤에 두는 이유는 <b>예산이 유한하기 때문</b>이다. 분당 호출 수는
     * 통로가 정하지 우리가 정하지 않는다.
     */
    DUMMY
}
